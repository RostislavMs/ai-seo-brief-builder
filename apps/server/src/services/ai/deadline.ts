/**
 * Стеля часу на всю роботу з моделлю в межах одного HTTP-запиту.
 *
 * Потрібна з тієї самої причини, що й спільний бюджет каскаду доступу
 * (fetcher/acquire.ts), але проти іншого супротивника. Там час обмежує терпіння
 * користувача, тут — ліміт тривалості serverless-функції: на Vercel це 300 с
 * (maxDuration у nitro.config.ts — стеля Fluid compute і на Hobby, і на Pro).
 * Коли генерація в них не вкладається, платформа вбиває функцію на півслові — і клієнт отримує 504
 * з тілом, яке навіть не JSON. Фронт у такому разі не має що показати, крім
 * «Помилка запиту (504)»: наше повідомлення про причину не існує, бо наш код
 * до обробника помилок не дійшов.
 *
 * Заміряно на проді: ТЗ помітно меншого обсягу впало по 504 там, де більше
 * пройшло. Розмір відповіді — не та змінна. Не залежать від нього одразу три
 * речі: другий запит при розбіжності зі схемою (request.ts), глибина
 * adaptive-мислення (вона про складність теми, не про обсяг) і власні повтори
 * SDK на 429 та 529. Кожна з них додає непередбачуваний час, тому межа
 * потрібна спільна, а не окрема на кожну.
 *
 * Механізм — саме сигнал розриву, а не опція `timeout` клієнта SDK. Різниця
 * принципова: таймаут SDK повторює (maxRetries за замовчуванням 2), тому
 * реальний час доходить до timeout × 3 і межа перестає бути межею. Обрив
 * користувачем SDK не повторює ніколи, тому один сигнал обмежує загальний час
 * незалежно від того, скільки повторів устигло статися всередині.
 */

export interface AiDeadline {
  /**
   * Сигнал для SDK провайдера. Спрацьовує і коли користувач натиснув
   * «Скасувати», і коли вичерпався бюджет, — SDK різниці не бачить, і не має.
   */
  readonly signal: AbortSignal | undefined;
  /**
   * true — час вичерпав саме бюджет, а не користувач. Різниця в тому, що
   * показувати: скасування — не збій і повідомлення не потребує, а вичерпаний
   * бюджет потребує, ще й із порадою.
   */
  expired(): boolean;
  /** Скільки часу лишилося. Infinity, якщо бюджету немає. */
  remainingMs(): number;
  /** Скільки часу було від початку. Infinity, якщо бюджету немає. */
  readonly budgetMs: number;
}

/**
 * Бюджет для одного запиту.
 *
 * `budgetMs` нуль або менше — бюджету немає, і лишається тільки сигнал
 * користувача: так поводиться локальна розробка, де ліміту функції не існує
 * і обрізати довгу генерацію нема причини.
 */
export function aiDeadline(
  budgetMs: number,
  requestSignal?: AbortSignal,
): AiDeadline {
  if (!Number.isFinite(budgetMs) || budgetMs <= 0) {
    return {
      signal: requestSignal,
      expired: () => false,
      remainingMs: () => Number.POSITIVE_INFINITY,
      budgetMs: Number.POSITIVE_INFINITY,
    };
  }

  const startedAt = Date.now();
  const timer = AbortSignal.timeout(budgetMs);

  return {
    // AbortSignal.any, а не власний AbortController: обидва джерела рівноправні,
    // а таймер від AbortSignal.timeout не тримає процес живим.
    signal: requestSignal ? AbortSignal.any([requestSignal, timer]) : timer,
    // Саме таймер, а не спільний сигнал: інакше скасування користувачем
    // виглядало б як вичерпаний бюджет і отримало б чуже повідомлення.
    expired: () => timer.aborted,
    remainingMs: () => Math.max(0, budgetMs - (Date.now() - startedAt)),
    budgetMs,
  };
}
