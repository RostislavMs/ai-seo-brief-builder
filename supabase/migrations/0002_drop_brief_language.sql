-- Мова ТЗ більше не налаштовується.
--
-- Вона визначається зі самих сторінок конкурентів
-- (services/brief/language.ts): ручний вибір лише розходився б із даними —
-- італійські конкуренти й «Українська» в налаштуваннях давали ТЗ, яке
-- не відповідає жодній із проаналізованих сторінок.
--
-- Разом із цим прибрано і резервний AI-ключ сервера: запити виконуються
-- виключно ключем користувача, тому active_provider = null тепер означає
-- «ключа немає», а не «працювати серверним».

alter table public.user_settings
  drop column if exists brief_language;

comment on column public.user_settings.active_provider is
  'Провайдер, чиїм ключем виконуються запити. null — ключа ще не додано, генерація ТЗ недоступна.';
