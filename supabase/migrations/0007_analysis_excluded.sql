-- Сторінка, яку користувач прибрав з основи для ТЗ.
--
-- Виконати у Supabase → SQL Editor після 0001–0006.
-- Скрипт ідемпотентний: повторний запуск нічого не ламає.
--
-- Каскад доступу витягує контент майже завжди, але «витягнуто» не означає
-- «годиться»: серед десяти адрес трапляється форум замість статті, лістинг
-- категорії або сторінка не про ту тему. Досі такий рядок або лишався в
-- промпті й тягнув ТЗ за собою, або доводилося створювати сесію заново без
-- нього — разом із повторним парсингом усіх решти.
--
-- Прапорець знімає цей вибір: сторінка лишається в сесії разом із розібраним
-- контентом, її видно й можна розгорнути, але в промпт вона не йде.

alter table public.session_analyses
  add column if not exists excluded boolean not null default false;

comment on column public.session_analyses.excluded is
  'true — сторінку виключено з основи для ТЗ: у промпти генерації, правок і порівняння вона не потрапляє. Розібраний контент лишається, тому повернути її в роботу можна без повторного парсингу.';

-- Індексу під цю колонку немає навмисно: сторінок у сесії максимум десять,
-- і читаються вони всі одразу за session_analyses_session_idx — окремий
-- індекс на прапорці лише подорожчав би запис результату парсингу.
