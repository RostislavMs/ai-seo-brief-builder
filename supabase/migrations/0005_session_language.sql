-- Мова контенту, задана вручну для сесії.
--
-- Виконати у Supabase → SQL Editor після 0001–0004.
-- Скрипт ідемпотентний: повторний запуск нічого не ламає.
--
-- Мова визначається зі самих сторінок конкурентів — з <html lang>, а коли його
-- немає, з характерних літер у заголовках. Другий шлях вгадує: італійські й
-- французькі діакритики перетинаються, і сторінка без lang може отримати чужу
-- мову. Помилка тут дорога: нею вибираються правила для промпта, і нею модель
-- пише весь контент ТЗ.
--
-- Тому колонка зберігає саме перевизначення, а не готову мову. NULL — звичайний
-- стан «вір визначеному»: сторінки можна проаналізувати заново, і мова
-- зміниться сама. Заповнене значення означає, що автовизначення помилилося, і
-- переживає повторний аналіз навмисно.

alter table public.sessions
  add column if not exists content_language text;

-- Обмеження окремим ALTER, а не всередині ADD COLUMN: якщо колонка вже є,
-- add column if not exists не виконується взагалі — разом із перевіркою.
--
-- Перевіряється лише форма коду ISO 639-1, а не належність до реєстру: реєстр
-- живе в коді (packages/shared/languages/registry.ts), і тримати його другу
-- копію в SQL означало б, що вони розійдуться. Валідність коду перевіряє
-- маршрут, а тут стоїть межа проти явного сміття.
alter table public.sessions
  drop constraint if exists sessions_content_language_check;

alter table public.sessions
  add constraint sessions_content_language_check
  check (content_language is null or content_language ~ '^[a-z]{2}$');
