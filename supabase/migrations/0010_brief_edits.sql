-- Ручна правка ТЗ: машинний оригінал поряд із робочою версією.
--
-- Виконати у Supabase → SQL Editor після 0001–0009.
-- Скрипт ідемпотентний: повторний запуск нічого не ламає.
--
-- ТЗ тепер редагується вручну — інлайн, просто в панелі (web/components/brief).
-- Через це в сесії співіснують дві версії того самого документа, і різниця між
-- ними — не історія, а робочий інструмент: саме вона відповідає на «що тут
-- моє, а що написала модель» і дає змогу повернути окреме поле, не втративши
-- решту правок.
--
-- Оригінал переписується щоразу, коли ТЗ приходить від моделі — і на генерації,
-- і на правці з чату. Це навмисно: чат отримує вже відредаговану версію й
-- повертає її разом зі своїми змінами, тому його відповідь — теж «машинна
-- версія», а не привід позначити чужу роботу як ручну.

alter table public.sessions
  add column if not exists original_brief jsonb;

comment on column public.sessions.original_brief is
  'ТЗ у тому вигляді, в якому його останнього разу віддала модель. Ним позначаються ручні правки й до нього повертає «Повернути згенероване».';

-- Наявним сесіям оригіналом стає їхнє ж поточне ТЗ.
--
-- Не null: сесія без оригіналу нічим не позначає ручні правки, і ТЗ, яке
-- користувач редагував до цієї міграції, показувало б «змінено» на кожному
-- полі — або, що гірше, «Повернути згенероване» повертало б порожнечу.
-- Прирівняти оригінал до поточного означає «розбіжностей поки немає», і це
-- єдине, що про такі сесії справді відомо.
update public.sessions
  set original_brief = brief
  where brief is not null
    and original_brief is null;
