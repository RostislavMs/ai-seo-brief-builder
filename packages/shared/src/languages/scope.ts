import { isLanguageCode } from "./registry";

/**
 * Область дії правила: конкретна мова або всі мови.
 *
 * Правило «не ставити крапку в кінці H2» не залежить від мови, і змушувати
 * писати його 183 рази — не варіант. Тому поряд із кодами ISO 639-1 існує
 * `"*"`: правило з таким кодом дописується в промпт для будь-якої мови.
 *
 * Сентинелом узято `"*"`, а не `"all"`: три літери можуть колись стати
 * кодом мови або збігтися з ним у чужих даних, а зірка — ні.
 */

/** Код правила, що діє для всіх мов. */
export const ALL_LANGUAGES = "*";

/**
 * Чи можна створити правило з таким кодом: або `"*"`, або код ISO 639-1.
 * Окремо від `isLanguageCode`, бо `"*"` — не мова, і решта коду не має
 * приймати його за мову.
 */
export function isRuleLanguage(code: string): boolean {
  return code === ALL_LANGUAGES || isLanguageCode(code);
}
