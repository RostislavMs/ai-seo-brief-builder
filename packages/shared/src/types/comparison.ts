/**
 * Аналіз власної сторінки відносно конкурентів (розділ 15 ТЗ).
 *
 * Це не ТЗ на нову статтю, а вирок наявній: чого на ній бракує з того, що
 * покривають конкуренти, і що з цим робити. Тому й тип окремий від SeoBrief.
 *
 * Поділ праці всередині звіту навмисний:
 *
 * - **арифметику рахує сервер** — обсяг, кількість заголовків, таблиць і FAQ,
 *   входження ключів, підсумковий бал. Це не творчість, і питати про це
 *   модель означало б платити токенами за числа, які й так лежать у даних,
 *   ще й отримувати їх приблизними;
 * - **зміст оцінює модель** — які розділи конкурентів не розкриті, які ключі
 *   взагалі варті уваги, як переписати title, у чому сторінка вже сильніша.
 *
 * Мови ті самі, що й у ТЗ: `instruction`, `verdict`, `action` і `strengths` —
 * англійською для райтера; заголовки, ключі та запропоновані title/H1 —
 * мовою проаналізованих сторінок.
 */

import type { Range } from "./brief";

/** Наскільки серйозна прогалина — вона ж черговість виправлення. */
export type GapSeverity = "critical" | "important" | "minor";

/**
 * Один показник власної сторінки поряд із конкурентами.
 *
 * Медіана, а не середнє: одна стаття на 12 000 слів серед п'яти
 * двотисячних зрушила б середнє так, що орієнтир перестав би бути орієнтиром.
 * `best` поруч потрібен, щоб було видно стелю, а не лише середину.
 */
export interface MetricComparison {
  own: number;
  /** Медіана по конкурентах. */
  median: number;
  /** Найбільше значення серед конкурентів. */
  best: number;
}

/** Набір показників, які рахуються однаково для всіх сторінок. */
export interface ComparisonMetrics {
  wordCount: MetricComparison;
  h2: MetricComparison;
  h3: MetricComparison;
  paragraphs: MetricComparison;
  lists: MetricComparison;
  tables: MetricComparison;
  faq: MetricComparison;
}

/**
 * Підсумковий бал і його складники, 0–100 кожен.
 *
 * Складники показуються поряд із загальним балом навмисно: саме число
 * без розкладу — чорна скринька, і довіряти йому немає підстав. Ваги
 * зафіксовані в коді (services/compare/metrics.ts), а не задаються моделлю:
 * інакше два запуски на тих самих даних дали б різні бали.
 */
export interface ComparisonScore {
  /** Зважена сума складників нижче. */
  total: number;
  /** Скільки розділів конкурентів розкрито; слабкі рахуються за половину. */
  structure: number;
  /** Обсяг відносно медіани конкурентів; понад медіану — стеля 100. */
  volume: number;
  /** Частка ключів конкурентів, які на сторінці вже вживаються. */
  keywords: number;
}

/**
 * Стан розділу власної сторінки.
 *
 * Окремого статусу «є лише в нас» немає навмисно: перевага сторінки — це
 * `strengths`, і дублювати її ще й тут означало б два переліки одного й того
 * самого, які модель заповнює по-різному.
 */
export type SectionStatus = "missing" | "weak" | "covered";

export interface ComparisonSection {
  /** Назва розділу мовою контенту. */
  title: string;
  status: SectionStatus;
  /** Скільки конкурентів розкривають цю тему. */
  competitors: number;
  /** Що з цим робити — англійською, для райтера. */
  instruction: string;
  /** Скільки слів дописати. Немає для status="covered". */
  addedWords?: Range;
}

/**
 * Ключ конкурентів і те, як із ним у нас.
 *
 * Обидва числа рахує сервер по повному тексту сторінок, а не модель:
 * «скільки разів слово трапляється в тексті» — пошук підрядка, і відповідь
 * на око тут гірша за відповідь точну.
 */
export interface ComparisonKeyword {
  /** Мовою контенту. */
  keyword: string;
  /** У скількох конкурентів зустрічається. */
  competitors: number;
  /** Скільки разів зустрічається на власній сторінці. 0 — ключа немає. */
  occurrences: number;
}

export type MetaField = "title" | "description" | "h1";

export interface ComparisonMetaIssue {
  field: MetaField;
  /** Що зараз на сторінці. null — поля немає взагалі. */
  current: string | null;
  /** Заміна мовою контенту. null — нинішнє значення годиться. */
  suggested: string | null;
  /** Чому саме так — англійською. */
  instruction: string;
}

/** Один крок плану. Порядок у масиві і є черговістю. */
export interface ComparisonAction {
  /** Англійською, наказовим способом. */
  action: string;
  severity: GapSeverity;
}

export interface PageComparison {
  /** Адреса власної сторінки на момент порівняння. */
  url: string;
  /** ISO-дата порівняння: сторінки могли змінитися після нього. */
  comparedAt: string;
  /** Скільки сторінок конкурентів брало участь у порівнянні. */
  competitorCount: number;
  /** Мова контенту англійською назвою — як і в SeoBrief. */
  contentLanguage: string;
  score: ComparisonScore;
  metrics: ComparisonMetrics;
  /** Підсумок 2–4 речення, англійською. */
  verdict: string;
  /** Розділи конкурентів і стан кожного в нас. */
  sections: ComparisonSection[];
  keywords: ComparisonKeyword[];
  /** Title, Meta Description і H1 — не більше трьох записів. */
  meta: ComparisonMetaIssue[];
  /** Чим сторінка вже краща за конкурентів. Англійською. */
  strengths: string[];
  /** Впорядкований план дій: найцінніше першим. */
  actions: ComparisonAction[];
}
