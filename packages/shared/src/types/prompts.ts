/**
 * Промпти, які можна правити на сайті. Спільний контракт web ↔ server.
 *
 * Промпт — це текст завдання для моделі зі вставками: `{{topic}}`,
 * `{{pagesJson}}`, `{{teamRules}}`. Початковий текст кожного промпта лежить
 * у коді сервера, а в базі зберігається лише правка адміна. Через це:
 *
 * - «скинути до початкового» завжди має що відновлювати, навіть якщо історія
 *   правок довга;
 * - разом із текстом сервер віддає перелік допустимих вставок, і клієнт не
 *   вгадує, що в цьому промпті взагалі можна написати.
 *
 * Права тут простіші, ніж у правил для мов: пропозицій немає. Користувач
 * бачить текст (за ним генерується його ТЗ), змінює лише адмін. Проміжного
 * стану «на розгляді» бути не може — промпт один, і поки він на розгляді,
 * генерувати ТЗ усе одно чимось треба.
 */

/**
 * Де працює текст. Групи задають порядок на сторінці, а не права:
 * `shared` — тексти, які дописуються в кілька промптів одразу, тому правка
 * тут зачіпає більше, ніж один сценарій.
 *
 * `document` — виняток серед решти: цей текст іде не в модель, а в саме ТЗ,
 * яке отримує райтер. Він тут тому, що потребує рівно того самого, що й
 * промпт, — початкового тексту в коді, правки лише адміном, історії й
 * скидання, — а друга така сама машинерія заради одного тексту дорожча
 * за одну зайву групу на цій сторінці.
 */
export type PromptGroup = "brief" | "chat" | "compare" | "shared" | "document";

/** Вставка в тексті промпта: `{{name}}`. */
export interface PromptVariable {
  /** Без дужок: `topic`, `pagesJson`. */
  name: string;
  description: string;
  /**
   * true — без цієї вставки промпт втрачає сенс, і зберегти його без неї
   * не можна. Наприклад `{{pagesJson}}`: промпт генерації без даних
   * конкурентів попросив би модель придумати ТЗ із нічого.
   */
  required: boolean;
}

export interface PromptTemplate {
  /** Ключ із реєстру сервера: `brief.system`, `compare.user`. */
  key: string;
  /** Назва українською — для сторінки, не для моделі. */
  title: string;
  /** Де саме цей текст використовується і що зміниться від правки. */
  description: string;
  group: PromptGroup;
  variables: PromptVariable[];
  /** Чинний текст: правка адміна або початковий, якщо правок не було. */
  body: string;
  /** Початковий текст із коду — для порівняння й скидання. */
  defaultBody: string;
  /** false — текст правили; чинний `body` відрізняється від початкового. */
  isDefault: boolean;
  /** Коли правили останнього разу. null — правок не було. */
  updatedAt: string | null;
  /** Пошта того, хто правив останнім. null — правок не було або акаунт видалено. */
  updatedByEmail: string | null;
  /** Скільки разів текст змінювали — разом зі скиданнями. */
  revisions: number;
}

/**
 * Одна редакція промпта.
 *
 * Зберігається повний текст, а не різниця: редакції порівнюють очима, і будь-яку
 * з них має бути видно цілком — саме так знаходять, коли промпт зламали.
 */
export interface PromptVersion {
  id: string;
  /** null — цією дією промпт скинули до початкового тексту. */
  body: string | null;
  /** Навіщо змінювали. */
  note: string | null;
  /** Пошта автора правки. null — акаунт видалено, редакція лишилася. */
  authorEmail: string | null;
  createdAt: string;
}

/** GET /api/prompts — усі промпти з чинним і початковим текстом. */
export interface PromptListResponse {
  prompts: PromptTemplate[];
}

/** GET /api/prompts/:key/history — редакції одного промпта, найновіші зверху. */
export interface PromptHistoryResponse {
  versions: PromptVersion[];
}

/**
 * PUT /api/prompts/:key — лише для адміна.
 *
 * PUT, а не PATCH: у промпта одне поле, і надіслати «частину тексту» не можна.
 * Текст, що дослівно дорівнює початковому, сервер приймає як скидання — інакше
 * «повернув як було руками» і «скинув кнопкою» дали б два різні стани.
 */
export interface UpdatePromptRequest {
  body: string;
  /** Навіщо змінювали — потрапляє в історію. */
  note?: string | null;
}

export interface PromptResponse {
  prompt: PromptTemplate;
}
