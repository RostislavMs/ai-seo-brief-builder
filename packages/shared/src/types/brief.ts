/**
 * Структура SEO ТЗ (розділ 9 ТЗ).
 *
 * Два правила, які визначають усю модель:
 *
 * 1. ТЗ віддається райтеру, тому **інструкції — англійською**.
 *    Це поля `instruction`.
 * 2. **Контент — мовою проаналізованих сторінок**: італійська, шведська,
 *    грецька — будь-яка. Це заголовки, ключі, питання, колонки таблиць.
 *
 * Тому в одному обʼєкті співіснують дві мови, і це навмисно.
 */

/**
 * Обсяг у ТЗ ніколи не буває точним числом — завжди діапазон:
 * 100-150 слів, 5500-5800 слів, 3-5 вживань ключа.
 */
export interface Range {
  min: number;
  max: number;
}

/**
 * Типи блоків, які трапляються в реальних ТЗ. Перелік закритий навмисно:
 * райтер має бачити знайому форму, а не довільний текст із варіаціями.
 */
export type BriefBlockKind =
  | "list"
  | "ordered_list"
  | "table"
  | "pros_cons"
  | "questions"
  | "highlight"
  | "links"
  | "template";

/**
 * Посилання, яке райтер має поставити в тексті.
 *
 * Порожній `url` — внутрішнє перелінкування, і таких посилань у ТЗ більшість.
 * Цільову сторінку свого сайту добирає SEO-фахівець, а не райтер і не модель,
 * тому ТЗ несе тільки анкор: в оригінальних документах агентства в колонці
 * URL у таких рядків стоїть `#`.
 *
 * Адреса заповнюється лише для зовнішнього авторитетного джерела —
 * регулятора, організації допомоги залежним, офіційного сайту бренду.
 * Сторінки конкурентів сюди не потрапляють ніколи: ТЗ пишеться, щоб їх
 * обійти, а не щоб на них послатися.
 */
export interface BriefLink {
  /** Анкор, мовою контенту. */
  anchor: string;
  /** Повна адреса зовнішнього джерела або порожньо — внутрішнє посилання. */
  url: string;
}

/**
 * Блок усередині розділу: список, таблиця, плюси-мінуси, питання, виділення,
 * посилання або шаблон повторюваного опису.
 *
 * Свідомо плоска структура з полем-дискримінатором замість обʼєднання типів:
 * структурований вивід моделі надійніше працює з однорідною схемою, ніж
 * з anyOf. Поля, нерелевантні для конкретного kind, лишаються порожніми.
 */
export interface BriefBlock {
  kind: BriefBlockKind;
  /** Що саме треба зробити — англійською, для райтера. */
  instruction: string;
  /**
   * kind="list" | "ordered_list" — пункти, які обовʼязково згадати.
   * kind="questions" — перелік питань (відповіді пише райтер).
   * kind="template" — сутності, кожну з яких треба описати за шаблоном.
   * Мовою контенту.
   */
  items: string[];
  /**
   * kind="table" — назви колонок, мовою контенту.
   * kind="template" — колонки таблиці всередині опису кожної сутності.
   */
  columns: string[];
  /** Підписи рядків, які райтер має заповнити. Ті самі два kind, що й columns. */
  rows: string[];
  /** kind="highlight" — саме речення, яке треба виділити. Мовою контенту. */
  text?: string;
  /** kind="links" — анкори та адреси. */
  links?: BriefLink[];
  /**
   * kind="template" — шаблон заголовка одного опису, напр.
   * `H3: №. {Brand Name} — {short bonus description}`.
   */
  itemTemplate?: string;
  /** kind="template" — обсяг опису однієї сутності. */
  itemWordCount?: Range;
  /** kind="pros_cons" | "template" — скільки переваг перелічити. */
  prosCount?: Range;
  /** kind="pros_cons" | "template" — скільки недоліків перелічити. */
  consCount?: Range;
}

/**
 * Текст між H1 і першим H2. У реальних ТЗ він є завжди, тому це окреме поле,
 * а не «нульовий розділ»: інакше модель то додає його як H2, то забуває зовсім.
 */
export interface BriefIntro {
  /** Інструкція англійською: що саме написати у вступі. */
  instruction: string;
  wordCount: Range;
  /** Скільки абзаців — у ТЗ це окрема вимога поряд з обсягом. */
  paragraphs: Range;
  /** Що вступ має розкрити. Мовою контенту. */
  mainPoints: string[];
  /** Ключі, які треба вжити у вступі. Мовою контенту. */
  keywords: string[];
}

/** H4 — найглибший рівень. Власних ключів і блоків не має. */
export interface BriefH4 {
  title: string;
  instruction: string;
  wordCount: Range;
}

export interface BriefH3 {
  title: string;
  instruction: string;
  wordCount: Range;
  keywords: string[];
  blocks: BriefBlock[];
  children: BriefH4[];
}

/** H2 — основна одиниця планування статті. */
export interface BriefH2 {
  title: string;
  /** Інструкція англійською: що описати в цьому розділі. */
  instruction: string;
  wordCount: Range;
  /** Ключі розділу без поділу на основні та другорядні. */
  keywords: string[];
  blocks: BriefBlock[];
  children: BriefH3[];
}

export interface BriefKeyword {
  keyword: string;
  /**
   * Скільки разів ключ має зустрітися в готовій статті — разом із заголовками,
   * таблицями й входженнями у складі довших ключів.
   */
  usage: Range;
}

/** Куди стає необовʼязкове доповнення: новий розділ, підрозділ або блок. */
export type BriefAdditionPlacement = "h2" | "h3" | "block";

/**
 * Те, що можна додати, але не обовʼязково. Обовʼязкове живе в `structure`
 * і в `blocks`: рекомендація, яку райтер має виконати, у списку «можна додати»
 * просто загубиться.
 */
export interface BriefOptionalAddition {
  placement: BriefAdditionPlacement;
  /** Заголовок нового розділу або назва блоку. Мовою контенту. */
  title: string;
  /**
   * Розділ зі `structure`, до якого це додається. Порожньо — місце
   * не принципове.
   */
  section: string;
  /** Скільки слів додасться до статті. */
  wordCount: Range;
  /** Що там написати і що це дає. Англійською. */
  instruction: string;
}

/**
 * Додаткові рекомендації: що можна додати понад план і що варто знати про
 * статтю в цілому.
 *
 * Списків «є в нас, немає в конкурентів» і навпаки тут немає навмисно. ТЗ
 * генерується лише з даних конкурентів — власна сторінка в цей промпт не
 * потрапляє за побудовою, — тому «нас» у ньому не існує: є лише структура,
 * яку модель щойно написала. Порівняння «наше проти їхнього» живе там, де для
 * нього є дані: в аналізі власної сторінки, який бачить обидві сторони й міряє
 * покриття, а не заявляє його.
 */
export interface BriefRecommendations {
  /** Необовʼязкові заголовки й блоки, які можна додати. */
  optionalAdditions: BriefOptionalAddition[];
  /** Загальні поради щодо структури. Англійською. */
  structureNotes: string[];
}

export interface SeoBrief {
  /**
   * Мова контенту, визначена з проаналізованих сторінок, англійською назвою:
   * "Italian", "Swedish", "Greek". Показується в інтерфейсі, щоб було видно,
   * якщо визначено неправильно.
   */
  contentLanguage: string;
  recommendedTitle: string;
  recommendedMetaDescription: string;
  recommendedH1: string;
  /** Інструкція англійською до статті в цілому: тон, аудиторія, акценти. */
  instruction: string;
  totalWordCount: Range;
  /** Текст після H1, до першого H2. */
  intro: BriefIntro;
  /** Ієрархія статті: H2 → H3 → H4. */
  structure: BriefH2[];
  /**
   * Зведена таблиця ключів усієї статті: сам ключ і кількість вживань.
   * Містить усі ключі, згадані у вступі та розділах, плюс основні запити теми,
   * тому це десятки рядків, а не короткий перелік.
   */
  keywords: BriefKeyword[];
  recommendations: BriefRecommendations;
}
