/**
 * Публічна версія сесії — те, що видно за посиланням без входу.
 *
 * Публікується не сесія, а її зліпок. Сесія — робоче місце: у ній
 * перезапускають аналіз, перегенеровують ТЗ і правлять його через чат. Якби
 * посилання читало сесію напряму, кожна така дія моментально змінювала б те,
 * що бачить клієнт, — включно з проміжними станами, яких показувати не
 * збиралися. Тому вміст замерзає на момент публікації, а оновлюється окремою
 * кнопкою.
 */

import type { ParsedPage } from "./page";
import type { SeoBrief } from "./brief";
import type { PageComparison } from "./comparison";

/**
 * Що з сесії йде в публічну версію.
 *
 * ТЗ у переліку немає: воно — сам результат роботи, і публікувати сесію без
 * нього нема сенсу, тому воно входить завжди, коли існує. Решта — окремо:
 * розібраний контент конкурентів і власна сторінка з балом стосуються не
 * лише автора, і показувати їх кожному, хто отримав посилання, треба за
 * явним вибором.
 */
export interface SharedSections {
  /** Сторінки конкурентів, з яких складено ТЗ. */
  analyses: boolean;
  /** Власна сторінка й звіт порівняння. */
  comparison: boolean;
}

/**
 * Сторінка в зліпку. Без id і статусу: id — внутрішній ключ рядка в базі,
 * а в зліпок потрапляють лише успішно розібрані сторінки, тому статус у ньому
 * завжди один і той самий.
 */
export interface SharedPage {
  url: string;
  analyzedAt: string | null;
  page: ParsedPage;
}

/** Замерзлий вміст публічної версії. Чату тут немає ніколи. */
export interface ShareSnapshot {
  name: string;
  topic: string;
  brief: SeoBrief | null;
  /** Сторінки конкурентів, які пішли в основу ТЗ. Порожньо — не публікували. */
  pages: SharedPage[];
  ownPage: SharedPage | null;
  comparison: PageComparison | null;
}

/** Публічна версія з точки зору власника сесії. */
export interface SessionShare {
  token: string;
  sections: SharedSections;
  /** Коли публічну версію створили або оновили. */
  publishedAt: string;
  /**
   * `updatedAt` сесії на момент зліпка. Саме з ним порівнюється поточний
   * `updatedAt`, щоб сказати власникові, що опубліковане відстало від робочого.
   */
  capturedAt: string;
}

/**
 * Публічна версія з точки зору того, хто відкрив посилання.
 *
 * Ні токена, ні id сесії, ні автора: токен читач уже має в адресному рядку,
 * а решта до вмісту ТЗ не стосується.
 */
export interface PublicShare {
  snapshot: ShareSnapshot;
  publishedAt: string;
}
